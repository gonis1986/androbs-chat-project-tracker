function cptDetectLanguage() {
  try {
    const saved = localStorage.getItem(CPT_LANGUAGE_KEY);
    if (CPT_LANGUAGES[saved]) return saved;
  } catch (e) { /* storage unavailable */ }
  const prefs = typeof navigator !== 'undefined' ? (navigator.languages || [navigator.language]) : [];
  for (const pref of prefs) {
    const code = String(pref || '').slice(0, 2).toLowerCase();
    if (CPT_LANGUAGES[code]) return code;
  }
  return 'en';
}

let cptCurrentLanguage = cptDetectLanguage();
if (typeof document !== 'undefined') document.documentElement.lang = cptCurrentLanguage;

function cptGetLanguage() {
  return cptCurrentLanguage;
}

function cptSetLanguage(lang, { persist = true } = {}) {
  if (!CPT_LANGUAGES[lang]) return false;
  const changed = lang !== cptCurrentLanguage;
  cptCurrentLanguage = lang;
  if (persist) {
    try { localStorage.setItem(CPT_LANGUAGE_KEY, lang); } catch (e) { /* storage unavailable */ }
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
  if (changed && typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('cpt:languagechange', { detail: { lang } }));
  }
  return true;
}

function cptT(key, params = {}, lang = cptCurrentLanguage) {
  const dict = CPT_I18N[lang] || CPT_I18N.en;
  const plural = typeof params.n === 'number' ? `${key}.${params.n === 1 ? 'one' : 'other'}` : null;
  const template = (plural && dict[plural]) || dict[key] ||
    (plural && CPT_I18N.en[plural]) || CPT_I18N.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

// The same key in every language (used to make category names searchable in any language).
function cptTAll(key) {
  return Object.keys(CPT_LANGUAGES).map(lang => cptT(key, {}, lang));
}

// Translates static markup: data-i18n (text), data-i18n-placeholder, data-i18n-title, data-i18n-aria-label,
// with optional JSON params in data-i18n-args.
function cptApplyI18n(root = document) {
  root.querySelectorAll('[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label]').forEach(el => {
    let args = {};
    if (el.dataset.i18nArgs) {
      try { args = JSON.parse(el.dataset.i18nArgs); } catch (e) { /* ignore bad args */ }
    }
    if (el.dataset.i18n) el.textContent = cptT(el.dataset.i18n, args);
    if (el.dataset.i18nPlaceholder) el.placeholder = cptT(el.dataset.i18nPlaceholder, args);
    if (el.dataset.i18nTitle) el.title = cptT(el.dataset.i18nTitle, args);
    if (el.dataset.i18nAriaLabel) el.setAttribute('aria-label', cptT(el.dataset.i18nAriaLabel, args));
  });
}
